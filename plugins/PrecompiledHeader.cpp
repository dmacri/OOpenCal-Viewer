const char* toString(CompilerFamily family)
{
    switch (family)
    {
    case CompilerFamily::Clang:
        return "clang";
    case CompilerFamily::Gcc:
        return "gcc";
    case CompilerFamily::Unknown:
        break;
    }
    return "unknown";
}

CompilerIdentity parseCompilerIdentity(const std::string& versionOutput)
{
    CompilerIdentity identity;
    identity.versionLine = firstLine(versionOutput);

    const std::string lower = toLower(versionOutput);
    if (lower.find("clang") != std::string::npos)
    {
        identity.family = CompilerFamily::Clang;
    }
    else if (lower.find("g++") != std::string::npos || lower.find("gcc") != std::string::npos ||
             lower.find("free software foundation") != std::string::npos)
    {
        identity.family = CompilerFamily::Gcc;
    }
    return identity;
}

CompilerIdentity identifyCompiler(const std::string& compilerPath)
{
#ifdef _WIN32
    (void)compilerPath;
    return {};
#else
    static std::mutex mutex;
    static std::map<std::string, CompilerIdentity> cache;
    {
        std::lock_guard lock(mutex);
        if (const auto it = cache.find(compilerPath); it != cache.end())
            return it->second;
    }

    // Names such as "g++" may be symlinks to clang (as in the AppImage), so only the real output is trusted
    std::string output;
    const std::string command = quote(compilerPath) + " --version 2>&1";
    if (FILE* pipe = popen(command.c_str(), "r"))
    {
        char buffer[512];
        while (std::fgets(buffer, sizeof(buffer), pipe) && output.size() < 8192)
        {
            output += buffer;
        }
        pclose(pipe);
    }

    const CompilerIdentity identity = parseCompilerIdentity(output);
    {
        std::lock_guard lock(mutex);
        cache[compilerPath] = identity;
    }
    return identity;
#endif
}

